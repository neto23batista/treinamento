test('atualiza o detalhe por evento Socket.IO versionado', async ({ page }) => {
  await page.goto('/nft/emerald-ape-042')
  await expect(page.getByRole('heading', { name: 'Emerald Ape #042' })).toBeVisible()
  await page.evaluate(() => window.dispatchEvent(new PointerEvent('pointerdown')))
  await page.waitForTimeout(500)
  const socket = io('http://127.0.0.1:3001', { transports: ['websocket'] })
  await new Promise<void>((resolve) => socket.on('connect', () => resolve()))
  socket.emit('demo:nft-update', { nftId: 'emerald-ape-042', price: 3.33 })
  await expect(page.getByRole('status')).toContainText('teve uma atualização de preço')
  await expect(page.locator('.detail-price')).toContainText('3.33 ETH')
  socket.disconnect()
})

